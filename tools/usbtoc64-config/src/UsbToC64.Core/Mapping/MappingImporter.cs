using UsbToC64.Core.Hid;
using UsbToC64.Core.Model;

namespace UsbToC64.Core.Mapping;

/// <summary>
/// Maps an existing profile (from a .h or .json) back onto the controls of the connected pad,
/// so it can be edited. Rules that do not correspond to any control are returned as unmatched.
/// </summary>
public static class MappingImporter
{
    public sealed record Result(PadMapping Mapping, IReadOnlyList<JmRule> UnmatchedRules, IReadOnlyList<byte> UnmatchedAxes);

    public static PadAction? FromFunc(JmFunc f) => f switch
    {
        JmFunc.Up => PadAction.Up, JmFunc.UpRight => PadAction.UpRight,
        JmFunc.Right => PadAction.Right, JmFunc.RightDown => PadAction.RightDown,
        JmFunc.Down => PadAction.Down, JmFunc.DownLeft => PadAction.DownLeft,
        JmFunc.Left => PadAction.Left, JmFunc.LeftUp => PadAction.LeftUp,
        JmFunc.Fire1 => PadAction.Fire1, JmFunc.Fire2 => PadAction.Fire2, JmFunc.Fire3 => PadAction.Fire3,
        JmFunc.AutofireOn => PadAction.AutofireOn, JmFunc.AutofireOff => PadAction.AutofireOff,
        JmFunc.AutofireHold => PadAction.AutofireHold,
        _ => null, // AUTO L/R: not supported by the dynamic engine
    };

    public static Result FromProfile(PadDescription pad, JmProfile profile)
    {
        var m = new PadMapping { Pad = pad };
        var unmatched = new List<JmRule>();
        var unmatchedAxes = new List<byte>();
        var usable = pad.Controls.Where(c => c.Supported).ToList();

        foreach (var r in profile.Rules)
        {
            if (FirmwareLimits.IsSigned(r.Op))
            {
                var axis = usable.FirstOrDefault(c => c.Kind == ControlKind.Axis && c.Signed && c.ByteIndex == r.Index);
                var act = r.Func is JmFunc.Left or JmFunc.Right ? PadAction.AxisX
                        : r.Func is JmFunc.Up or JmFunc.Down ? PadAction.AxisY : PadAction.None;
                if (axis != null && act != PadAction.None) m.Set(axis, act);
                else unmatched.Add(r);
                continue;
            }
            if (r.Op == JmOp.Hat)
            {
                var hat = usable.FirstOrDefault(c => c.Kind == ControlKind.Hat && c.ByteIndex == r.Index
                                                     && r.Value >= c.HatBase && r.Value < c.HatBase + c.HatPositions);
                if (hat != null) m.Set(hat, PadAction.Directions);
                else unmatched.Add(r);
                continue;
            }

            // BIT rules, and "==" rules on a single bit (generated by the web SAVE for buttons).
            bool singleBit = r.Value != 0 && (r.Value & (r.Value - 1)) == 0;
            var btn = (r.Op == JmOp.BitAny || singleBit)
                ? usable.FirstOrDefault(c => c.Kind is ControlKind.Button or ControlKind.DpadButton
                                             && c.ByteIndex == r.Index && c.Mask == r.Value)
                : null;
            var action = FromFunc(r.Func);
            if (btn != null && action != null && m.Get(btn) == PadAction.None)
                m.Set(btn, action.Value);
            else
                unmatched.Add(r);
        }

        void Axes(IEnumerable<byte> idxs, PadAction a)
        {
            foreach (var idx in idxs)
            {
                var ax = usable.FirstOrDefault(c => c.Kind == ControlKind.Axis && c.ByteIndex == idx && m.Get(c) == PadAction.None);
                if (ax != null) m.Set(ax, a);
                else unmatchedAxes.Add(idx);
            }
        }
        Axes(profile.AnalogX, PadAction.AxisX);
        Axes(profile.AnalogY, PadAction.AxisY);

        return new Result(m, unmatched, unmatchedAxes);
    }
}
